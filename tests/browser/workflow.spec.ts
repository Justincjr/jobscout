import { test, expect } from '@playwright/test';

test('review profile → paste job → inspect evidence → edit/export → track application', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Find your next chapter.' })).toBeVisible();
  await page.getByRole('button', { name: 'Career profile', exact: true }).click();
  await page.getByLabel('Fact type', { exact: true }).selectOption('experience');
  await page.getByLabel('Fact', { exact: true }).fill('Engineer at Acme, 2022–2025. Built React dashboards.');
  await page.getByRole('button', { name: 'Add for review' }).click();
  await page.getByLabel('Fact type', { exact: true }).selectOption('skill');
  await page.getByLabel('Fact', { exact: true }).fill('React');
  await page.getByRole('button', { name: 'Add for review' }).click();
  await page.getByRole('checkbox', { name: /^Select fact/ }).first().check();
  await page.getByRole('checkbox', { name: /^Select fact/ }).nth(1).check();
  await page.getByRole('button', { name: 'Confirm reviewed selection (2)' }).click();
  await expect(page.getByText('Ready for personalized matching')).toBeVisible();
  await page.getByRole('button', { name: 'Discover', exact: true }).click();
  await page.getByRole('button', { name: 'Add a job', exact: true }).click();
  await page.getByLabel('Job title', { exact: true }).fill('Frontend Engineer');
  await page.getByLabel('Company', { exact: true }).fill('Synthetic Acme');
  await page.getByLabel('Job description', { exact: true }).fill('Requirements\nExperience with React\nResponsibilities\nBuild accessible dashboards.');
  await page.getByRole('button', { name: 'Add job', exact: true }).click();
  await page.getByRole('button', { name: 'Explore role', exact: true }).first().click();
  await page.getByRole('button', { name: 'Evidence', exact: true }).click();
  await expect(page.getByText('Evidence, not guesswork.')).toBeVisible();
  await page.getByRole('button', { name: 'Application workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Create from confirmed facts (no AI)' }).click();
  await expect(page.getByLabel('Application draft', { exact: true })).toHaveValue(/Engineer at Acme/);
  await page.getByRole('checkbox', { name: 'I have reviewed this draft and its factual accuracy.' }).check();
  await page.getByRole('button', { name: 'Save revision', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download TXT', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('resume.txt');
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.getByLabel('Date applied', { exact: true }).fill('2026-10-16');
  await page.getByRole('button', { name: 'Mark as applied', exact: true }).click();
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: /^My applications/ }).click();
  await page.getByLabel('Application status', { exact: true }).selectOption('applied');
  await expect(page.getByRole('button', { name: 'Frontend Engineer', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/workflow-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/workflow-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
